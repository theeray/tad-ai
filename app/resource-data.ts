export type ResourceStatus = "verified" | "tad-built" | "review" | "reference";

export type Resource = {
  name: string;
  category: string;
  domains?: string[];
  status: ResourceStatus;
  summary: string;
  url: string;
  exampleUrl?: string;
  note?: string;
  tags: string[];
};

